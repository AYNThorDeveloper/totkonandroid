#!/usr/bin/env python3
"""Vulkan entry points as function pointers for the game loader.
Scans the given sources for vk* calls and writes <out>.h (externs, forced in
with -include and VK_NO_PROTOTYPES) and <out>.c (the pointers and a loader
that fills them from a vkGetInstanceProcAddr, so the system driver or a
custom driver opened through libadrenotools can be used).
usage: gen_vk_dispatch.py <out base> <source.c>..."""
import re
import sys
from pathlib import Path

GLOBAL = {'vkCreateInstance', 'vkEnumerateInstanceExtensionProperties', 'vkEnumerateInstanceLayerProperties',
          'vkEnumerateInstanceVersion'}
SKIP = {'vkGetInstanceProcAddr'}   # the loader's own entry point
EXTENSION = {'vkGetMemoryFdKHR', 'vkCmdSetVertexInputEXT'}   # fetched where used


def main():
    out, sources = Path(sys.argv[1]), sys.argv[2:]
    names = set()
    for s in sources:
        names |= set(re.findall(r'\b(vk[A-Z]\w+)\s*\(', Path(s).read_text()))
    names -= SKIP | EXTENSION
    names = sorted(n for n in names if not n.startswith('vk_'))
    h = ['/* Generated by gen_vk_dispatch.py; do not edit. */', '#pragma once',
         '#include <vulkan/vulkan.h>']
    h += ['extern PFN_%s %s;' % (n, n) for n in names]
    h += ['extern PFN_vkGetInstanceProcAddr vkGetInstanceProcAddr;',
          '/* Global entry points from the loader, then the rest once the instance exists. */',
          'void nvk_dispatch_load_global(PFN_vkGetInstanceProcAddr gipa);',
          'void nvk_dispatch_load_instance(VkInstance instance);']
    c = ['/* Generated by gen_vk_dispatch.py; do not edit. */', '#include <stdio.h>', '#include "%s.h"' % out.name,
         'extern _Noreturn void runtime_fail(const char *message);']
    c += ['PFN_%s %s;' % (n, n) for n in names]
    c += ['PFN_vkGetInstanceProcAddr vkGetInstanceProcAddr;',
          'void nvk_dispatch_load_global(PFN_vkGetInstanceProcAddr gipa) {', '    vkGetInstanceProcAddr = gipa;']
    for n in names:
        if n in GLOBAL:
            c.append('    %s = (PFN_%s)gipa(VK_NULL_HANDLE, "%s");' % (n, n, n))
    c += ['    if (!vkCreateInstance) runtime_fail("Vulkan loader without vkCreateInstance");', '}',
          'void nvk_dispatch_load_instance(VkInstance instance) {']
    for n in names:
        if n not in GLOBAL:
            c.append('    %s = (PFN_%s)vkGetInstanceProcAddr(instance, "%s");' % (n, n, n))
            c.append('    if (!%s) { fprintf(stderr, "[android-gfx] Vulkan entry %s missing\\n", "%s"); runtime_fail("Vulkan entry point missing"); }' % (n, '%s', n))
    c.append('}')
    out.with_suffix('.h').write_text('\n'.join(h) + '\n')
    out.with_suffix('.c').write_text('\n'.join(c) + '\n')
    print('%d Vulkan entry points' % len(names))


if __name__ == '__main__':
    main()
